import { test, expect } from '@playwright/test';
import { mkdirSync } from 'node:fs';
const screenshotDir = '../docs/screenshots';
test('public walkthrough: evidence, Spanish, full family loop, reset and responsive layout', async ({ page }, info) => {
  const errors: string[] = []; page.on('pageerror',e => errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{ name: 'Life gets complicated. Family makes it clearer.' })).toBeVisible();
  await page.getByRole('button',{ name: 'Show original evidence' }).click();
  await expect(page.getByText('Exact line from the fictional letter')).toBeVisible();
  await page.getByRole('button',{ name: 'Español',exact: true }).click();
  await expect(page.getByText('Comunícate con la compañía sobre el saldo pendiente.')).toBeVisible();
  await page.getByRole('button',{ name: 'Ask Sam for help',exact: true }).click();
  await expect(page.getByRole('heading',{ name: 'Help is on the way.' })).toBeVisible();
  await page.getByRole('button',{ name: 'Sam accepts task',exact: true }).click();
  await expect(page.getByRole('heading',{ name: 'Someone has her back.' })).toBeVisible();
  await page.getByRole('button',{ name: 'Sam reports completion',exact: true }).click();
  await expect(page.getByText('Sam reported completing the follow-up. María has been updated.')).toBeVisible();
  await page.getByRole('button',{ name: 'Restart walkthrough',exact: true }).click();
  await expect(page.getByRole('heading',{ name: 'A letter, made clear.' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
  mkdirSync(screenshotDir,{ recursive: true });
  if (info.project.name === 'desktop') {
    await page.getByRole('button',{ name: 'English',exact: true }).click();
    await page.screenshot({ path: `${screenshotDir}/desktop-walkthrough.png`,fullPage: true });
    await page.locator('#family-view').screenshot({ path: `${screenshotDir}/desktop-family-preview.png` });
  } else await page.locator('#family-view').screenshot({ path: `${screenshotDir}/mobile-family-preview.png` });
});
test('private dashboard: login, real local API data, filters, translation, refresh and logout', async ({ page,context }, info) => {
  const errors: string[] = []; page.on('pageerror',e => errors.push(e.message));
  await page.goto('/family');
  await expect(page.getByRole('button',{ name: 'Open my circle' })).toBeEnabled();
  await page.getByLabel('Family password').fill('wrong-password');
  await page.getByRole('button',{ name: 'Open my circle' }).click();
  await expect(page.locator('.family-error[role=alert]')).toContainText('Incorrect password');
  await page.getByLabel('Family password').fill('clearcircle-test-password');
  await page.getByRole('button',{ name: 'Open my circle' }).click();
  await expect(page.getByRole('heading',{ name: 'Small steps. Shared responsibility.' })).toBeVisible();
  await expect(page.locator('.live-letter')).toHaveCount(2);
  await page.getByRole('button',{ name: 'Needs attention',exact: true }).click();
  await expect(page.locator('.live-letter')).toHaveCount(1);
  await page.getByRole('button',{ name: 'Acciones en español' }).click();
  await expect(page.getByText('Comunícate con la compañía sobre el saldo pendiente.')).toBeVisible();
  await page.getByRole('button',{ name: 'Reported complete',exact: true }).click();
  await expect(page.locator('.live-letter')).toHaveCount(1);
  await expect(page.getByText('Completion is helper reported; payment or resolution is not independently verified.')).toBeVisible();
  await page.getByRole('button',{ name: 'All letters',exact: true }).click();
  await page.getByRole('button',{ name: 'Refresh',exact: true }).click();
  await expect(page.locator('.live-letter')).toHaveCount(2);
  const cookie = (await context.cookies()).find(c => c.name === 'clearcircle-family');
  expect(cookie?.httpOnly).toBe(true); expect(cookie?.secure).toBe(true); expect(cookie?.sameSite).toBe('Strict');
  expect(await page.evaluate(() => document.cookie)).not.toContain('clearcircle-family');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
  await page.screenshot({ path: `${screenshotDir}/${info.project.name}-private-dashboard.png`,fullPage: true });
  await page.getByRole('button',{ name: 'Sign out',exact: true }).click();
  await expect(page.getByLabel('Family password')).toBeVisible();
  expect((await page.request.get('/api/dashboard')).status()).toBe(401);
});
test('unauthenticated, tampered-session and cross-origin requests cannot access family data', async ({ request,context }) => {
  expect((await request.get('/api/dashboard')).status()).toBe(401);
  await context.addCookies([{ name: 'clearcircle-family',value: 'forged',domain: '127.0.0.1',path: '/' }]);
  expect((await context.request.get('/api/dashboard')).status()).toBe(401);
  expect((await request.post('/api/session',{ headers: { Origin: 'https://untrusted.example' },data: { password: 'clearcircle-test-password' } })).status()).toBe(403);
  expect((await request.delete('/api/session',{ headers: { Origin: 'https://untrusted.example' } })).status()).toBe(403);
});
test('dashboard shows offline errors and never replaces live data with demo content', async ({ page }) => {
  await page.route('**/api/dashboard',route => route.fulfill({ status: 502,json: { error: 'Cannot reach the family agent. Check that it is running, then refresh.' } }));
  await page.goto('/family');
  await expect(page.locator('.family-error[role=alert]')).toContainText('Cannot reach the family agent');
  await expect(page.locator('.live-letter')).toHaveCount(0);
  await expect(page.getByText('Peach State Utilities')).toHaveCount(0);
});
